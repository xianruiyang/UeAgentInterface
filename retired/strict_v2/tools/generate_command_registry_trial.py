from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any


DEFAULT_SOURCE = Path(
    "Plugins/UeAgentInterface/Source/UeAgentInterface/Private/Server/CommandSources/NodeGraph.command_source.json"
)
DEFAULT_TARGET = Path(
    "Plugins/UeAgentInterface/Source/UeAgentInterface/Private/Server/Generated/UeAgentCommandRegistry_NodeGraphExact.h"
)
ALLOWED_INVOKERS = {
    "InvokeExactWithCtx",
    "InvokeExactNoCtx",
    "InvokeExactWithCtxArtifacts",
    "InvokeExactMutableWithCtx",
}


def load_source(path: Path) -> dict[str, Any]:
    with path.open("r", encoding="utf-8") as handle:
        data = json.load(handle)
    if data.get("schema") != "uai.command_source.v1":
        raise ValueError(f"Unsupported schema in {path}: {data.get('schema')!r}")
    if not isinstance(data.get("commands"), list) or not data["commands"]:
        raise ValueError(f"No commands declared in {path}")
    return data


def validate_command(command: dict[str, Any]) -> None:
    name = command.get("name")
    if not isinstance(name, str) or not name or name != name.lower():
        raise ValueError(f"Invalid command name: {name!r}")
    if command.get("lifecycle") != "active":
        raise ValueError(f"Trial generator only accepts active commands: {name}")
    dispatch = command.get("dispatch")
    if not isinstance(dispatch, dict):
        raise ValueError(f"Missing dispatch object for {name}")
    if dispatch.get("kind") != "exact":
        raise ValueError(f"Trial generator only accepts exact commands: {name}")
    handler = dispatch.get("handler_symbol")
    if not isinstance(handler, str) or not handler.startswith("Cmd"):
        raise ValueError(f"Invalid handler symbol for {name}: {handler!r}")
    invoker = dispatch.get("invoker_template")
    if invoker not in ALLOWED_INVOKERS:
        raise ValueError(f"Invalid invoker template for {name}: {invoker!r}")
    documentation = command.get("documentation")
    if not isinstance(documentation, dict) or not documentation.get("doc_file"):
        raise ValueError(f"Missing documentation.doc_file for {name}")
    coverage = command.get("coverage")
    if not isinstance(coverage, dict) or not coverage.get("smoke_files"):
        raise ValueError(f"Missing coverage.smoke_files for {name}")


def render_include(source: Path, commands: list[dict[str, Any]]) -> str:
    lines = [
        "// Generated by scripts/uai/generate_command_registry_trial.py.",
        f"// Source: {source.as_posix()}",
        "// Do not edit manually.",
    ]
    for command in commands:
        validate_command(command)
        dispatch = command["dispatch"]
        name = command["name"]
        invoker = dispatch["invoker_template"]
        handler = dispatch["handler_symbol"]
        lines.append(
            f'\t\t\t\t{{ TEXT("{name}"), &{invoker}<&FUeAgentHttpServer::{handler}> }},'
        )
    return "\n".join(lines) + "\n"


def write_or_check(target: Path, content: str, check: bool) -> bool:
    if check:
        if not target.exists():
            raise FileNotFoundError(f"Generated registry include is missing: {target}")
        current = target.read_text(encoding="utf-8")
        return current == content
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(content, encoding="utf-8", newline="\n")
    return True


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate/check the P4 trial command registry include.")
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE)
    parser.add_argument("--target", type=Path, default=DEFAULT_TARGET)
    parser.add_argument("--check", action="store_true", help="Fail if the generated include is stale.")
    args = parser.parse_args()

    source = args.source
    target = args.target
    data = load_source(source)
    commands = data["commands"]
    content = render_include(source, commands)
    is_current = write_or_check(target, content, args.check)
    result = {
        "schema": "uai.command_registry_trial_generation.v1",
        "source": str(source),
        "target": str(target),
        "command_count": len(commands),
        "check": bool(args.check),
        "current": bool(is_current),
    }
    print(json.dumps(result, indent=2))
    return 0 if is_current else 1


if __name__ == "__main__":
    raise SystemExit(main())
